@alerts_bp.route("/<alert_id>/read", methods=["PATCH", "POST"])
def mark_alert_read(alert_id: str):
    """Backward-compatible endpoint: alias for acknowledge."""
    return acknowledge_alert(alert_id)


@alerts_bp.route("/notifications", methods=["GET"])
def list_notifications():
    """Returns unacknowledged / active alerts formatted as notifications."""
    Session = get_session_factory()
    session = Session()
    try:
        _ensure_alerts_seeded(session)
        active_alerts = Repository.get_alerts(session, status="ACTIVE")
        notifs = []
        for a in active_alerts:
            notifs.append({
                "id": a.id,
                "alert_id": a.id,
                "title": a.title,
                "message": a.description,
                "severity": (a.severity or "INFO").lower(),
                "category": a.type or "system",
                "is_read": bool(a.is_acknowledged),
                "created_at": a.created_at.isoformat() + "Z" if a.created_at else None,
            })
        return jsonify({
            "notifications": notifs,
            "total": len(notifs),
            "unread": len(notifs),
        })
    finally:
        session.close()


