"""
Alerts & Incident Command API Routes — Phase 10.

Connects to the canonical database table `alerts` to provide:
- Real-time persisted system alerts generated by events
- Filtering by severity, status, source, habitation, and site
- Acknowledgement and resolution workflows with timestamp audit trails
- Deep links to associated habitations and relocation sites
"""
from flask import Blueprint, request, jsonify
from app.db.database import get_session_factory
from app.db.repository import Repository
from app.engines.alert_engine import AlertEngine

alerts_bp = Blueprint("alerts", __name__)


def _ensure_alerts_seeded(session):
    """If the alerts table is completely empty, run baseline system audit to seed initial alerts."""
    from app.db.models import Alert
    count = session.query(Alert).count()
    if count == 0:
        AlertEngine.audit_and_seed_system_alerts(session)



@alerts_bp.route("", methods=["GET"])
@alerts_bp.route("/list", methods=["GET"])
def list_alerts():
    """
    List all persisted alerts from the database.
    Supports query filters:
    - severity: CRITICAL, HIGH, WARNING, INFO, ALL
    - status: ACTIVE, UNACKNOWLEDGED, ACKNOWLEDGED, RESOLVED, ALL
    - source: FIELD_VERIFICATION, OPTIMIZER, SIMULATION, etc.
    - habitation_id: filter by specific habitation
    - site_id: filter by specific candidate site
    """
    Session = get_session_factory()
    session = Session()
    try:
        _ensure_alerts_seeded(session)

        severity = request.args.get("severity")
        status = request.args.get("status")
        source = request.args.get("source")
        hab_id = request.args.get("habitation_id")
        site_id = request.args.get("site_id")

        alerts = Repository.get_alerts(
            db=session,
            severity=severity,
            status=status,
            source=source,
            habitation_id=hab_id,
            site_id=site_id
        )

        all_alerts = Repository.get_alerts(db=session)

        summary = {
            "total": len(all_alerts),
            "critical": len([a for a in all_alerts if (a.severity or "").upper() == "CRITICAL"]),
            "high": len([a for a in all_alerts if (a.severity or "").upper() == "HIGH"]),
            "warning": len([a for a in all_alerts if (a.severity or "").upper() == "WARNING"]),
            "info": len([a for a in all_alerts if (a.severity or "").upper() == "INFO"]),
            "unacknowledged": len([a for a in all_alerts if not a.is_acknowledged and not a.is_resolved]),
            "resolved": len([a for a in all_alerts if a.is_resolved]),
        }

        return jsonify({
            "alerts": [Repository.alert_to_dict(a) for a in alerts],
            "total": len(alerts),
            "summary": summary,
        })
    finally:
        session.close()


@alerts_bp.route("/<alert_id>/acknowledge", methods=["PATCH", "POST"])
def acknowledge_alert(alert_id: str):
    """Acknowledge a specific alert."""
    Session = get_session_factory()
    session = Session()
    try:
        alert = Repository.acknowledge_alert(session, alert_id)
        if not alert:
            return jsonify({"error": f"Alert {alert_id} not found"}), 404

        session.commit()
        return jsonify({
            "status": "success",
            "message": f"Alert {alert_id} acknowledged.",
            "alert": Repository.alert_to_dict(alert),
        })
    finally:
        session.close()


